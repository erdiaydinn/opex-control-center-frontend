export function translateAcademyOperationalReadiness(locale, key) {
  return ACADEMY_OPERATIONAL_READINESS_MESSAGES[locale]?.[key]
    || ACADEMY_OPERATIONAL_READINESS_MESSAGES.en[key]
    || key;
}

export function academyOperationalReadinessMessageCoverage(locales) {
  const keys = Object.keys(ACADEMY_OPERATIONAL_READINESS_MESSAGES.en).sort();
  return {
    missing: Object.fromEntries(
      locales.map((locale) => [
        locale,
        keys.filter(
          (key) => typeof ACADEMY_OPERATIONAL_READINESS_MESSAGES[locale]?.[key] !== "string",
        ),
      ]),
    ),
    extra: Object.fromEntries(
      locales.map((locale) => [
        locale,
        Object.keys(ACADEMY_OPERATIONAL_READINESS_MESSAGES[locale] || {})
          .filter((key) => !keys.includes(key))
          .sort(),
      ]),
    ),
  };
}
