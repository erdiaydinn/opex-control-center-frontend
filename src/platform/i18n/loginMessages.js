export function translateLogin(locale, key) {
  return LOGIN_MESSAGES[locale]?.[key] || LOGIN_MESSAGES.en[key] || key;
}

export function loginMessageCoverage(locales) {
  const keys = Object.keys(LOGIN_MESSAGES.en).sort();
  return {
    missing: Object.fromEntries(locales.map((locale) => [locale, keys.filter((key) => typeof LOGIN_MESSAGES[locale]?.[key] !== "string")])),
    extra: Object.fromEntries(locales.map((locale) => [locale, Object.keys(LOGIN_MESSAGES[locale] || {}).filter((key) => !keys.includes(key)).sort()])),
  };
}
