export function translatePlanogramEconomics(locale, key, params = {}) {
  const message = PLANOGRAM_ECONOMICS_MESSAGES[locale]?.[key];
  const fallback = PLANOGRAM_ECONOMICS_MESSAGES.en[key];
  const template = typeof message === "string" ? message : fallback || key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}
