export function translatePlanogramPreview(locale, key, params = {}) {
  const message = PLANOGRAM_PREVIEW_MESSAGES[locale]?.[key];
  const fallback = PLANOGRAM_PREVIEW_MESSAGES.en[key];
  const template = typeof message === "string" ? message : fallback || key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}

export function planogramPreviewMessageCoverage(locales) {
  const keys = Object.keys(PLANOGRAM_PREVIEW_MESSAGES.en).sort();
  return {
    missing: Object.fromEntries(
      locales.map((locale) => [
        locale,
        keys.filter((key) => typeof PLANOGRAM_PREVIEW_MESSAGES[locale]?.[key] !== "string"),
      ])
    ),
    extra: Object.fromEntries(
      locales.map((locale) => [
        locale,
        Object.keys(PLANOGRAM_PREVIEW_MESSAGES[locale] || {}).filter((key) => !keys.includes(key)).sort(),
      ])
    ),
  };
}
