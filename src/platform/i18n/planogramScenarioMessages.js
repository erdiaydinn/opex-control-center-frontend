export function translatePlanogramScenario(locale, key, params = {}) {
  const message = PLANOGRAM_SCENARIO_MESSAGES[locale]?.[key];
  const fallback = PLANOGRAM_SCENARIO_MESSAGES.en[key];
  const template = typeof message === "string" ? message : fallback || key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}
