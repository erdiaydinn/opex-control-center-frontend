export function translatePlatformHealth(locale, key, params = {}) {
  const message = PLATFORM_HEALTH_MESSAGES[locale]?.[key];
  const fallback = PLATFORM_HEALTH_MESSAGES.en[key];
  const template = typeof message === "string" ? message : fallback || key;
  return template.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}

export function platformHealthMessageCoverage(locales) {
  const keys = Object.keys(PLATFORM_HEALTH_MESSAGES.en).sort();
  return {
    missing: Object.fromEntries(
      locales.map((locale) => [
        locale,
        keys.filter((key) => typeof PLATFORM_HEALTH_MESSAGES[locale]?.[key] !== "string"),
      ])
    ),
    extra: Object.fromEntries(
      locales.map((locale) => [
        locale,
        Object.keys(PLATFORM_HEALTH_MESSAGES[locale] || {}).filter((key) => !keys.includes(key)).sort(),
      ])
    ),
  };
}
