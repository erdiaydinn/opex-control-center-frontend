export function translateProduct(locale, key, params = {}) {
  const message = PRODUCT_MESSAGES[locale]?.[key];
  if (typeof message !== "string") return null;
  return message.replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}

export function productMessageCoverage() {
  const referenceKeys = Object.keys(PRODUCT_MESSAGES.en).sort();
  return {
    referenceKeys,
    missing: Object.fromEntries(
      Object.entries(PRODUCT_MESSAGES).map(([locale, messages]) => [
        locale,
        referenceKeys.filter((key) => typeof messages[key] !== "string"),
      ])
    ),
  };
}
