const MESSAGES = { tr, en, de, ar, fr, es, it, nl, pl, "pt-BR": ptBR };
const STATUS_KEYS = {
  PENDING_EMPLOYEE_ACCEPTANCE: "statusPendingEmployee",
  OPEN_FOR_ACCEPTANCE: "statusOpen",
  PENDING_MANAGER_APPROVAL: "statusPendingManager",
  APPROVED: "statusApproved",
  REJECTED: "statusRejected",
  CANCELLED: "statusCancelled",
};

export function workforceShiftTradeMessage(locale, key, params = {}) {
  const dictionary = MESSAGES[locale] || MESSAGES.en;
  const template = dictionary[key] || MESSAGES.en[key] || key;
  return String(template).replace(/\{(\w+)\}/g, (_, token) => String(params[token] ?? `{${token}}`));
}

export function workforceShiftTradeStatusMessage(locale, status) {
  return workforceShiftTradeMessage(locale, STATUS_KEYS[status] || "statusOpen");
}
